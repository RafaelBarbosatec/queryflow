import 'package:queryflow/src/dialect/mysql_dialect.dart';
import 'package:queryflow/src/dialect/postgres_sql_dialect.dart';

import '../database_type.dart';
import '../dialect/sql_dialect.dart';
import 'table_column_types.dart';

export 'table_column_types.dart';

class TableModel {
  final String name;
  final Map<String, TableColumnType> columns;
  final String engine;
  final int outomaticIncrement;
  final String charset;
  final List<List<dynamic>>? initalData;

  TableModel({
    required this.name,
    required this.columns,
    this.engine = 'InnoDB',
    this.outomaticIncrement = 1,
    this.charset = 'utf8mb4',
    this.initalData,
  });

  String get primaryKeyColumn {
    String name = '';
    columns.forEach(
      (key, value) {
        if (name.isEmpty && value.isPrimaryKey) {
          name = key;
        }
      },
    );
    return name;
  }

  /// Column names that can be provided on insert, excluding auto increment
  /// columns that are generated by the database.
  List<String> get insertableColumns => columns.entries
      .where((entry) => !entry.value.isAutoIncrement)
      .map((entry) => entry.key)
      .toList();

  /// Builds the full definition of [columnName], including type, nullability,
  /// default value, auto increment, unique and enum constraints.
  ///
  /// Used both by [toCreateSql] and by schema synchronization when adding new
  /// columns, so both paths produce the same definition.
  String columnDefinition(String columnName, SqlDialect dialect) {
    final columnType = columns[columnName];
    if (columnType == null) {
      throw ArgumentError('Column $columnName not found in table $name');
    }

    final quotedColumn = dialect.quoteIdentifier(columnName);
    var columnDef = '$quotedColumn ${columnType.getTypeName(dialect)}';

    // PostgreSQL has no inline ENUM type, so the allowed values are enforced
    // with a CHECK constraint instead.
    if (columnType is TypeEnum && dialect is PostgreSqlDialect) {
      columnDef +=
          ' CHECK ($quotedColumn IN (${_quoteEnumValues(columnType.values)}))';
    }

    if (columnType.isNotNull || columnType.isPrimaryKey) {
      columnDef += ' NOT NULL';
    }
    if (columnType.isAutoIncrement) {
      columnDef = dialect.getAutoIncrementSyntax(columnDef);
    }
    if (columnType.isUnique && !columnType.isPrimaryKey) {
      columnDef += ' UNIQUE';
    }
    if (columnType.defaultValue != null) {
      if (_isString(columnType)) {
        columnDef += " DEFAULT '${columnType.defaultValue}'";
      } else {
        columnDef += ' DEFAULT ${columnType.defaultValue}';
      }
    }
    if (columnType.onUpdate != null && dialect is MySqlDialect) {
      columnDef += ' ON UPDATE ${columnType.onUpdate}';
    }

    return columnDef;
  }

  String toCreateSql([SqlDialect? dialect]) {
    final d = dialect ?? SqlDialect.create(DatabaseType.mysql);
    StringBuffer sql =
        StringBuffer('CREATE TABLE ${d.quoteIdentifier(name)} (\n');
    List<String> columnDefinitions = [];
    List<String> primaryKeys = [];
    Map<String, TableColumnType> foreignKeys = {};

    columns.forEach((columnName, columnType) {
      columnDefinitions.add(columnDefinition(columnName, d));
      if (columnType.foreignKey != null) {
        foreignKeys.addAll({columnName: columnType});
      }
      if (columnType.isPrimaryKey) {
        primaryKeys.add(d.quoteIdentifier(columnName));
      }
    });

    if (primaryKeys.isNotEmpty) {
      columnDefinitions.add('PRIMARY KEY (${primaryKeys.join(', ')})');
    }

    foreignKeys.forEach((columnName, columnType) {
      final fk = columnType.foreignKey!;
      columnDefinitions.add(
        'CONSTRAINT ${d.quoteIdentifier(fk.getKeyName(name, columnName))} ${d.getForeignKeySyntax(columnName, fk.table, fk.column)}',
      );
    });

    sql.writeAll(columnDefinitions, ', \n');
    sql.write('\n)');

    // Só adiciona opções específicas do MySQL se o dialect for MySQL
    if (d is MySqlDialect) {
      sql.write(' ENGINE=$engine');
      sql.write(' AUTO_INCREMENT=$outomaticIncrement');
      sql.write(' DEFAULT CHARSET=$charset');
    }
    sql.write(';');
    return sql.toString();
  }

  int get columnsToInsert =>
      columns.values.where((e) => e.isAutoIncrement == false).length;

  /// Builds an INSERT statement for [columnNames] (or all insertable columns by
  /// default) using the placeholders required by [dialect].
  String toInsertSql([
    SqlDialect? dialect,
    List<String>? columnNames,
  ]) {
    final d = dialect ?? SqlDialect.create(DatabaseType.mysql);
    final names = columnNames ?? insertableColumns;
    if (names.isEmpty) {
      throw ArgumentError(
        "Table '$name' has no insertable columns",
      );
    }

    final placeholders = List.generate(
      names.length,
      (index) => d.getPlaceholder(index + 1),
    );
    return 'INSERT INTO ${d.quoteIdentifier(name)} '
        '(${names.map(d.quoteIdentifier).join(', ')}) '
        'VALUES (${placeholders.join(', ')});';
  }

  final List<String> _defaultValues = [
    'CURRENT_TIMESTAMP',
    'CURRENT_DATE',
    'CURRENT_TIME',
    'LOCALTIME',
    'LOCALTIMESTAMP',
  ];

  bool _isString(TableColumnType columnType) {
    if (_defaultValues.contains(columnType.defaultValue)) {
      return false;
    }
    return columnType is TypeVarchar ||
        columnType is TypeText ||
        columnType is TypeEnum ||
        columnType is TypeDateTime ||
        columnType is TypeTime ||
        columnType is TypeDate;
  }

  String _quoteEnumValues(List<String> values) {
    return values.map((value) => "'${value.replaceAll("'", "''")}'").join(', ');
  }
}
